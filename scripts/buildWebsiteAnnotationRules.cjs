'use strict';
// Build-time only. The website's DOM-free TypeScript is the source of truth;
// production Node executes this checked-in artifact without Angular or TypeScript.
const fs = require('fs'), path = require('path'), crypto = require('crypto'), ts = require('typescript');
const sourceRoot = path.resolve(__dirname, '../../RoznaComarker/src/app');
const entries = ['components/correction-overlay/annotation-geometry', 'components/correction-overlay/annotation-layout',
    'components/correction-overlay/annotation-image-geometry'];
function build() {
    const sources = {}, factories = {}, dependencies = {};
    function visit(id) {
        if (factories[id])
            return;
        const file = path.join(sourceRoot, id + '.ts'), source = fs.readFileSync(file, 'utf8');
        sources[id] = crypto.createHash('sha256').update(source).digest('hex');
        const code = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS,
                removeComments: true } }).outputText;
        factories[id] = code;
        dependencies[id] = {};
        for (const match of code.matchAll(/require\("([^"]+)"\)/g)) {
            if (!match[1].startsWith('.'))
                throw Error('DOM-free annotation rules must have local dependencies only');
            const dependency = path.posix.normalize(path.posix.join(path.posix.dirname(id), match[1]));
            dependencies[id][match[1]] = dependency;
            visit(dependency);
        }
    }
    entries.forEach(visit);
    return "'use strict';\n// GENERATED by scripts/buildWebsiteAnnotationRules.cjs. Do not hand edit.\n"
        + 'const sourceHashes=' + JSON.stringify(sources, null, 2) + ';\nconst dependencies=' + JSON.stringify(dependencies) + ';\nconst factories={\n'
        + Object.entries(factories).map(([id, code]) => JSON.stringify(id) + ':function(module,exports,require){\n' + code + '\n}').join(',\n')
        + '\n};\nconst cache={};function load(id){if(cache[id])return cache[id].exports;const module={exports:{}};cache[id]=module;'
        + 'factories[id](module,module.exports,name=>load(dependencies[id][name]));return module.exports;}\n'
        + 'module.exports={sourceHashes,...load(' + JSON.stringify(entries[0]) + '),...load(' + JSON.stringify(entries[1]) + '),...load(' + JSON.stringify(entries[2]) + ')};\n';
}
if (require.main === module) {
    fs.writeFileSync(path.resolve(__dirname, '../src/pdf/websiteAnnotationRules.generated.js'), build());
}
module.exports = { build };
